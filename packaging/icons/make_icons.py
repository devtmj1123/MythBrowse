"""MythBrowse app icon: writes the SVG masters and every raster from one geometry.

Design (flat liquid glass, JustMyth tokens, ui/design/tokens.css):
  * a rounded-square tile of MythDesk sky, dusk-blue at the top (#2b4386) to the day blue
    (#6698d2) at the bottom: dark enough that the pastel dots read on light and dark taskbars;
  * a frosted glass pane (white 10-34 % sheen, 1 px white rim): the browser window, and the
    message Myth is writing;
  * across it the three Myth dots of the title-bar mark, in a row: lilac #a99bff, sky #7fd3ff,
    pink #ff9cc6.
At 16-24 px the pane is dropped (it turns to mush) and the dots grow, so the mark stays three
clean dots on the tile.

Run: python3 packaging/icons/make_icons.py   (needs Pillow). Outputs (committed):
  packaging/icons/mythbrowse.svg, mythbrowse-small.svg, png/mythbrowse-<N>.png
  packaging/windows/mythbrowse.ico                 16,20,24,32,40,48,64,96,128,256
  packaging/windows/msix/Assets/*.png              MSIX logos (+ targetsize-N variants)
  crates/shell/resources/icon-32.png, icon-256.png runtime window / taskbar icon
  ui/design/logo.svg                               in-app logo (onboarding, About)
"""
import io, os, struct
from PIL import Image, ImageDraw, ImageFilter

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
TOP, BOTTOM = (0x2B, 0x43, 0x86), (0x66, 0x98, 0xD2)
DOTS = [(0xA9, 0x9B, 0xFF), (0x7F, 0xD3, 0xFF), (0xFF, 0x9C, 0xC6)]
# Geometry on a 1-unit square.
TILE_R = 0.225          # corner radius
LENS = (0.165, 0.315, 0.835, 0.685, 0.185)  # x0, y0, x1, y1, radius: a glass pane (window / message)
DOT_R = 0.072
DOT_POS = [(0.5 - 0.17, 0.5), (0.5, 0.5), (0.5 + 0.17, 0.5)]
# Small sizes: no pane, larger dots.
DOT_R_SMALL = 0.118
DOT_POS_SMALL = [(0.5 - 0.27, 0.5), (0.5, 0.5), (0.5 + 0.27, 0.5)]
RIM_ALPHA = 0.5

def hexc(c): return "#%02x%02x%02x" % c

def svg(small=False):
    dots = DOT_POS_SMALL if small else DOT_POS
    dr = DOT_R_SMALL if small else DOT_R
    s = 256
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {s} {s}" width="{s}" height="{s}">',
           '<!-- MythBrowse icon (JustMyth). Generated by packaging/icons/make_icons.py. -->',
           '<defs><linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">'
           f'<stop offset="0" stop-color="{hexc(TOP)}"/><stop offset="1" stop-color="{hexc(BOTTOM)}"/></linearGradient>',
           '<linearGradient id="sheen" x1="0" y1="0" x2="0" y2="1">'
           '<stop offset="0" stop-color="#ffffff" stop-opacity="0.34"/>'
           '<stop offset="0.55" stop-color="#ffffff" stop-opacity="0.10"/>'
           '<stop offset="1" stop-color="#ffffff" stop-opacity="0.16"/></linearGradient></defs>',
           f'<rect x="0" y="0" width="{s}" height="{s}" rx="{TILE_R*s:.1f}" fill="url(#sky)"/>']
    if not small:
        x0, y0, x1, y1, r = (v * s for v in LENS)
        out.append(f'<rect x="{x0:.1f}" y="{y0:.1f}" width="{x1-x0:.1f}" height="{y1-y0:.1f}" rx="{r:.1f}" fill="url(#sheen)"/>')
        out.append(f'<rect x="{x0+1:.1f}" y="{y0+1:.1f}" width="{x1-x0-2:.1f}" height="{y1-y0-2:.1f}" rx="{r-1:.1f}" fill="none" stroke="#ffffff" stroke-opacity="{RIM_ALPHA}" stroke-width="2"/>')
    for (x, y), c in zip(dots, DOTS):
        out.append(f'<circle cx="{x*s:.1f}" cy="{y*s:.1f}" r="{dr*s:.1f}" fill="{hexc(c)}"/>')
    out.append('</svg>')
    return "\n".join(out) + "\n"

def render(n):
    """Raster at n px: drawn 8x larger and downsampled (same geometry as the SVG)."""
    small = n <= 24
    k = 8
    S = n * k
    img = Image.new("RGBA", (S, S), (0, 0, 0, 0))
    # Tile gradient through a rounded mask.
    grad = Image.new("RGBA", (1, S))
    for y in range(S):
        t = y / (S - 1)
        grad.putpixel((0, y), tuple(round(TOP[i] + (BOTTOM[i] - TOP[i]) * t) for i in range(3)) + (255,))
    grad = grad.resize((S, S))
    mask = Image.new("L", (S, S), 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, S - 1, S - 1], radius=TILE_R * S, fill=255)
    img.paste(grad, (0, 0), mask)
    d = ImageDraw.Draw(img, "RGBA")
    if not small:
        x0, y0, x1, y1, r = (v * S for v in LENS)
        # Sheen: white, stronger at the top (vertical gradient clipped to the pane).
        sheen = Image.new("RGBA", (S, S), (0, 0, 0, 0))
        for y in range(int(y0), int(y1) + 1):
            t = (y - y0) / (y1 - y0)
            a = 0.34 + (0.10 - 0.34) * min(t / 0.55, 1) if t < 0.55 else 0.10 + (0.16 - 0.10) * (t - 0.55) / 0.45
            ImageDraw.Draw(sheen).line([(0, y), (S, y)], fill=(255, 255, 255, round(255 * a)))
        lm = Image.new("L", (S, S), 0)
        ImageDraw.Draw(lm).rounded_rectangle([x0, y0, x1, y1], radius=r, fill=255)
        img = Image.alpha_composite(img, Image.composite(sheen, Image.new("RGBA", (S, S), (0, 0, 0, 0)), lm))
        d = ImageDraw.Draw(img, "RGBA")
        # Rim: 1 px at the final size (at least 2/256 of the tile).
        w = max(k * 1.0, 2 / 256 * S)
        rim = Image.new("RGBA", (S, S), (0, 0, 0, 0))
        ImageDraw.Draw(rim).rounded_rectangle([x0, y0, x1, y1], radius=r, outline=(255, 255, 255, round(255 * RIM_ALPHA)), width=round(w))
        img = Image.alpha_composite(img, rim)
        d = ImageDraw.Draw(img, "RGBA")
    dots, dr = (DOT_POS_SMALL, DOT_R_SMALL) if small else (DOT_POS, DOT_R)
    for (x, y), c in zip(dots, DOTS):
        d.ellipse([(x - dr) * S, (y - dr) * S, (x + dr) * S, (y + dr) * S], fill=c + (255,))
    return img.resize((n, n), Image.LANCZOS)

def ico(images, path):
    """Windows .ico with PNG-compressed entries (Vista+ reads PNG entries at every size)."""
    blobs = []
    for im in images:
        b = io.BytesIO(); im.save(b, "PNG"); blobs.append(b.getvalue())
    head = struct.pack("<HHH", 0, 1, len(images))
    off = 6 + 16 * len(images)
    dirs = b""
    for im, data in zip(images, blobs):
        w = im.width if im.width < 256 else 0
        dirs += struct.pack("<BBBBHHII", w, w, 0, 0, 1, 32, len(data), off)
        off += len(data)
    with open(path, "wb") as f:
        f.write(head + dirs + b"".join(blobs))

def on_canvas(n_canvas_w, n_canvas_h, icon_px):
    im = Image.new("RGBA", (n_canvas_w, n_canvas_h), (0, 0, 0, 0))
    ic = render(icon_px)
    im.paste(ic, ((n_canvas_w - icon_px) // 2, (n_canvas_h - icon_px) // 2), ic)
    return im

def main():
    p = lambda *a: os.path.join(ROOT, *a)
    os.makedirs(p("packaging", "icons", "png"), exist_ok=True)
    open(p("packaging", "icons", "mythbrowse.svg"), "w").write(svg())
    open(p("packaging", "icons", "mythbrowse-small.svg"), "w").write(svg(small=True))
    open(p("ui", "design", "logo.svg"), "w").write(svg())
    sizes = [16, 20, 24, 32, 40, 48, 64, 96, 128, 256]
    imgs = {n: render(n) for n in sizes + [44, 50, 71, 150, 310, 512]}
    for n in sizes + [512]:
        imgs[n].save(p("packaging", "icons", "png", f"mythbrowse-{n}.png"))
    ico([imgs[n] for n in sizes], p("packaging", "windows", "mythbrowse.ico"))
    imgs[32].save(p("crates", "shell", "resources", "icon-32.png"))
    imgs[256].save(p("crates", "shell", "resources", "icon-256.png"))
    a = p("packaging", "windows", "msix", "Assets")
    # MSIX tiles: the icon fills ~66 % of square tiles (Windows' own tile padding look).
    imgs[44].save(os.path.join(a, "Square44x44Logo.png"))
    for n in (16, 24, 32, 48, 256):
        imgs[n].save(os.path.join(a, f"Square44x44Logo.targetsize-{n}.png"))
        imgs[n].save(os.path.join(a, f"Square44x44Logo.targetsize-{n}_altform-unplated.png"))
    imgs[50].save(os.path.join(a, "StoreLogo.png"))
    on_canvas(71, 71, 48).save(os.path.join(a, "Square71x71Logo.png"))
    on_canvas(150, 150, 100).save(os.path.join(a, "Square150x150Logo.png"))
    on_canvas(310, 310, 206).save(os.path.join(a, "Square310x310Logo.png"))
    on_canvas(310, 150, 100).save(os.path.join(a, "Wide310x150Logo.png"))
    print("icons written")

if __name__ == "__main__":
    main()
